function decodeRuns(path, tailCommand, tailCount) {
    const runs = ROUTE_PREFIX.map((run) => [...run]);
    const merge = (command, count) => {
        if (count === 0) return;
        if (runs.at(-1)[0] === command) runs.at(-1)[1] += count;
        else runs.push([command, count]);
    };
    for (const command of path) merge(Number(command), 12);
    merge(tailCommand, tailCount);
    return runs;
}

