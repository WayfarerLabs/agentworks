"""Removal of the workspace tmuxinator projects that releases up to 0.19 generated.

Those releases wrote ``.tmuxinator.yml`` into each workspace and linked it from the
admin's ``~/.config/tmuxinator/`` as ``ws-<name>-console.yml``. Admin-side
configuration does not belong in workspace content, so the feature is removed and
``vm reinit`` retires what it left behind:

- Every ``ws-*-console.yml`` entry in the admin's ``~/.config/tmuxinator/`` that is a
  symlink whose target ends in ``/.tmuxinator.yml``, as every generated one did, is
  removed, dangling or not. Only the link goes; its target is never followed.
- A workspace's ``.tmuxinator.yml`` is removed when it is a regular file that starts
  with the header those releases wrote, whoever owns it: the header alone decides,
  and only that many bytes are compared. Anything else stays.

What the admin cannot reach or read well enough to judge, and anything whose removal
fails, stays in place and is reported: reinit warns once, and a rerun once access is
restored finishes the job.
"""

from __future__ import annotations

import re
import shlex
from typing import TYPE_CHECKING

from agentworks import output
from agentworks.errors import ValidationError
from agentworks.execution.envelope import argument_bytes
from agentworks.execution.requests import Command
from agentworks.workspaces.guest import REQUEST_FAILURES

if TYPE_CHECKING:
    from collections.abc import Sequence

    from agentworks.execution.access import VMAccess

_GENERATED_HEADER = b"# Generated by agentworks. Changes will be overwritten.\n"
_PROJECT_NAME = ".tmuxinator.yml"
# Linux refuses to look up a path of this many bytes or more in one call.
_LOOKUP_LIMIT = 4096
_UNFINISHED_MARKER = "AGW_TMUXINATOR_UNFINISHED="
_FINISHED_MARKER = "AGW_TMUXINATOR_FINISHED"
_UNFINISHED_LINE = re.compile(f"{_UNFINISHED_MARKER}([1-9][0-9]{{0,8}})".encode())
_DEADLINE = 60
"""Seconds each of the two commands may take."""

# Each script records a failure in ``rc`` and keeps going, so one entry cannot hide
# another's failure or stop the rest. A test that is merely false never sets it;
# being unable to search or read something does.
#
# Both scripts first try to enter a directory with ``cd -P`` in a subshell, which
# succeeds only when the kernel lets the admin reach and search it. When it fails,
# ``vacant`` says whether the kernel shows nothing can be there: the path exists as
# something other than a directory, or it does not exist (and is not a link) and the
# nearest existing ancestor can be entered or is not a directory. Anything else, such
# as a directory the admin cannot search, a link that leads nowhere or through one, or
# a relative path, cannot be judged; the ``/*`` test also ends the walk, since
# stripping the last component leaves a path with no slash unchanged. It walks up in a
# loop, since a shell's function recursion is too shallow for a deep path, and an
# empty step means the root, because ``cd ""`` stays in the working directory under
# dash and bash. A path too long for the kernel to look up cannot be judged either,
# yet it fails as a missing one would and the walk then reaches a shorter ancestor, so
# ``_judgeable`` keeps such workspace paths from being sent. An admin ``HOME`` that
# long is not guarded.
_VACANT_FUNCTION = """\
vacant() {
  candidate=$1
  while :; do
    if [ -e "$candidate" ]; then [ ! -d "$candidate" ]; return; fi
    [ ! -L "$candidate" ] || return 1
    case $candidate in /*) ;; *) return 1 ;; esac
    candidate=${candidate%/*}
    candidate=${candidate:-/}
    (cd -P -- "$candidate") 2>/dev/null && return 0
  done
}
"""

# ``$(...)`` strips every trailing newline, and a link's target may end in one, so
# ``x`` guards the output and ``%??`` drops it with the one newline readlink adds,
# leaving the exact target. A failed readlink leaves it empty. A ``HOME`` that is not
# absolute leads into some other tree: an empty one names ``/.config``, and a relative
# one resolves against the command's working directory. Either fails before anything
# is entered.
_LINKS_SCRIPT = (
    _VACANT_FUNCTION
    + """\
case $HOME in /*) ;; *) exit 1 ;; esac
dir="$HOME/.config/tmuxinator"
(cd -P -- "$dir") 2>/dev/null || { vacant "$dir"; exit; }
[ -r "$dir" ] || exit 1
rc=0
for link in "$dir"/ws-*-console.yml; do
  target=$(readlink -- "$link" 2>/dev/null && printf x)
  case ${target%??} in
    */.tmuxinator.yml) rm -f -- "$link" || rc=1 ;;
  esac
done
exit "$rc"
"""
)

# Workspace paths arrive as arguments. ``[ -f ]`` and ``[ ! -L ]`` keep a FIFO, a
# directory or a link away from ``cmp``, which exits 1 on a difference and 2 when it
# cannot read. Each workspace the script could not finish is reported by its argument
# position on a marker line of its own, so the caller names it from the path it sent
# rather than from output, which a path holding a line break would split. A last
# marker line says the loop reached the end of its arguments, so a run that died
# partway is not taken to have failed only where it reported.
_PROJECTS_SCRIPT = (
    _VACANT_FUNCTION
    + f"""\
header={shlex.quote(_GENERATED_HEADER.decode())}
rc=0
position=0
unfinished() {{ rc=1; printf '{_UNFINISHED_MARKER}%s\\n' "$position"; }}
for workspace do
  position=$((position + 1))
  if (cd -P -- "$workspace") 2>/dev/null; then
    project="$workspace/{_PROJECT_NAME}"
    if [ -f "$project" ] && [ ! -L "$project" ]; then
      printf %s "$header" | cmp -s -n {len(_GENERATED_HEADER)} -- "$project" -
      case $? in
        0) rm -f -- "$project" || unfinished ;;
        1) ;;
        *) unfinished ;;
      esac
    fi
  elif ! vacant "$workspace"; then
    unfinished
  fi
done
printf '{_FINISHED_MARKER}\\n'
exit "$rc"
"""
)


# Each script runs as the admin under ``sh -c``, its argv carried inside the request
# rather than on a command line, so no shell of the admin's parses the script or the
# paths, and the script's stdin is at end of file. The workspace paths travel as
# arguments, each as the bytes ``argument_bytes`` gives it.
# The guest kernel caps the arguments and environment of one command together at
# ``ARG_MAX`` (2 MiB under the default 8 MiB stack limit), tens of thousands of
# typical workspace paths, far above any real VM; beyond it the guest refuses the
# command and reinit warns.
def _run(access: VMAccess, script: str, *arguments: str) -> tuple[bool, bytes]:
    """Run one script with these arguments; whether it exited 0, and its stdout.

    An outcome that is not an exit status raises its typed error.
    """
    result = access.run(Command(("sh", "-c", script, "sh", *arguments), deadline=_DEADLINE))
    return result.require_completed(access.vm_name) == 0, result.stdout


def _judgeable(workspace_path: str) -> bool:
    """Whether the projects command can judge this path: absolute, and with a project
    path that the request can carry (``argument_bytes``: no NUL, and encodable as
    UTF-8 with ``surrogateescape``) and whose bytes stay under the kernel's lookup
    limit. The project path adds only ASCII, so the workspace path the command is
    sent can be carried exactly when it can."""
    if not workspace_path.startswith("/"):
        return False
    try:
        project_path = argument_bytes(f"{workspace_path}/{_PROJECT_NAME}")
    except ValidationError:
        return False
    return len(project_path) < _LOOKUP_LIMIT


def retire_tmuxinator_projects(access: VMAccess, workspace_paths: Sequence[str]) -> list[str]:
    """Remove the admin's generated discovery links and these workspaces' generated projects.

    Both commands always run, so one failure never leaves the rest of the VM
    uncleaned. A path the projects command cannot judge is skipped and counted.
    Returns a description of each failure, empty when everything finished; what
    succeeded stays done, and a rerun is safe.
    """
    judgeable = [path for path in workspace_paths if _judgeable(path)]
    failures: list[str] = []
    if skipped := len(workspace_paths) - len(judgeable):
        failures.append(
            f"{output.count(skipped, 'workspace path')} skipped as not absolute, holding a NUL byte "
            "or a character with no UTF-8 encoding, or too long to look up"
        )
    try:
        if not _run(access, _LINKS_SCRIPT)[0]:
            failures.append("the discovery links could not all be checked or removed")
    except REQUEST_FAILURES:
        failures.append("the discovery-link command could not run or did not report back")
    try:
        ok, stdout = _run(access, _PROJECTS_SCRIPT, *judgeable)
    except REQUEST_FAILURES:
        failures.append("the workspace-project command could not run or did not report back")
    else:
        # The guest's output is input, so only a whole marker line counts, and an
        # unfinished one only when it names an argument that was sent. A run that did
        # not report finishing, or failed naming nothing, is also reported as a whole.
        lines = stdout.split(b"\n")
        numbers = [int(match[1]) for line in lines if (match := _UNFINISHED_LINE.fullmatch(line))]
        unfinished = list(dict.fromkeys(judgeable[number - 1] for number in numbers if number <= len(judgeable)))
        if unfinished:
            failures.append(f"the projects in {', '.join(unfinished)} could not be checked or removed")
        if _FINISHED_MARKER.encode() not in lines or (not ok and not unfinished):
            failures.append("the workspace projects could not all be checked or removed")
    return failures
