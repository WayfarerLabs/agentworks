"""Removal of the workspace tmuxinator projects that releases up to 0.19 generated.

Those releases wrote ``.tmuxinator.yml`` into each workspace and linked it from the
admin's ``~/.config/tmuxinator/`` as ``ws-<name>-console.yml``. Admin-side
configuration does not belong in workspace content, so the feature is removed and
``vm reinit`` retires what it left behind:

- Every ``ws-*-console.yml`` entry in the admin's ``~/.config/tmuxinator/`` that is a
  symlink whose target ends in ``/.tmuxinator.yml``, as every generated one did, is
  removed, dangling or not. Only the link goes; its target is never followed.
- A workspace's ``.tmuxinator.yml`` is removed when it is a regular file that starts
  with the header those releases wrote. Only that many bytes are compared. Anything
  else stays.

Both commands run under ``sh -c`` as the admin, so the admin's login shell never
parses them, and both always run. A discovery directory that cannot be read or
searched, a project file that cannot be read and anything an unsearchable directory
hides stay in place and count as failures, as does a failed removal. The caller
warns once, naming the workspaces the project command reports it could not finish.
When that command cannot run over SSH, the warning says so. When it runs but does
not report reading every path it was sent, or fails without naming any workspace,
the warning also says the projects could not all be checked.
"""

from __future__ import annotations

import re
import shlex
from typing import TYPE_CHECKING

from agentworks import output
from agentworks.ssh import SSHError

if TYPE_CHECKING:
    from collections.abc import Sequence

    from agentworks.transports import Transport

_GENERATED_HEADER = b"# Generated by agentworks. Changes will be overwritten.\n"
_UNFINISHED_MARKER = "AGW_TMUXINATOR_UNFINISHED="
_FINISHED_MARKER = "AGW_TMUXINATOR_FINISHED="
_PATHS_SENTINEL = "AGW_TMUXINATOR_PATHS"
_UNFINISHED_LINE = re.compile(f"{_UNFINISHED_MARKER}([1-9][0-9]{{0,8}})")
_FINISHED_LINE = re.compile(f"{_FINISHED_MARKER}(0|[1-9][0-9]{{0,8}})")

# Each script records a failure in ``rc`` and keeps going, so one entry cannot hide
# another's failure or stop the rest. A test that is merely false never sets it;
# being unable to search or read something does.
#
# ``$(...)`` strips every trailing newline, and a path may end in one, so a
# substitution that yields a path appends ``x`` and ``%??`` drops it with the one
# newline the command adds, leaving the exact path. A failed command leaves it empty.
#
# ``hidden`` resolves links in a path with ``realpath -m`` and walks up from it to the
# nearest path that exists. What is in or below the path is hidden when that is a
# directory the admin cannot search.
_HIDDEN_FUNCTION = """\
hidden() {
  up=$(realpath -m -- "$1" && printf x)
  up=${up%??}
  until [ -e "$up" ]; do
    case $up in */*) up="${up%/*}" ;; *) return 1 ;; esac
  done
  [ -d "$up" ] && [ ! -x "$up" ]
}
"""

_LINKS_SCRIPT = (
    _HIDDEN_FUNCTION
    + """\
dir="$HOME/.config/tmuxinator"
if [ ! -d "$dir" ]; then
  hidden "$dir" && exit 1
  exit 0
fi
[ -x "$dir" ] && [ -r "$dir" ] || exit 1
rc=0
for link in "$dir"/ws-*-console.yml; do
  target=$(readlink -- "$link" 2>/dev/null && printf x)
  case ${target%??} in
    */.tmuxinator.yml) rm -f -- "$link" || rc=1 ;;
  esac
done
exit "$rc"
"""
)

# Workspace paths arrive one per line on stdin, after a fixed first line the script
# checks before reading any. Something that reads stdin before the script, such as a
# startup file of the admin's shell, can only take from the start, so it changes that
# line, and the script then exits 3 without reading or reporting anything.
#
# ``[ -f ]`` and ``[ ! -L ]`` keep a FIFO, a directory or a link away from ``cmp``,
# which exits 1 on a difference and 2 when it cannot read. A project hidden by an
# unsearchable directory, whether its workspace or one above it, counts as a failure
# too. Each workspace the script could not finish is reported by its line number on a
# marker line of its own, so the caller names it from the path it sent rather than
# from output that line-ending translation may have changed. A last marker line gives
# how many paths the script read. The caller takes the run as complete only when that
# count is how many it sent, and trusts no line number from a run that reports a
# different count.
_PROJECTS_SCRIPT = (
    _HIDDEN_FUNCTION
    + f"""\
header={shlex.quote(_GENERATED_HEADER.decode())}
IFS= read -r first && [ "$first" = {_PATHS_SENTINEL} ] || exit 3
rc=0
line=0
unfinished() {{ rc=1; printf '\\n{_UNFINISHED_MARKER}%s\\n' "$line"; }}
while IFS= read -r workspace; do
  line=$((line + 1))
  project="$workspace/.tmuxinator.yml"
  if [ -f "$project" ] && [ ! -L "$project" ]; then
    printf %s "$header" | cmp -s -n {len(_GENERATED_HEADER)} -- "$project" -
    case $? in
      0) rm -f -- "$project" || unfinished ;;
      1) ;;
      *) unfinished ;;
    esac
  elif hidden "$workspace"; then
    unfinished
  fi
done
printf '\\n{_FINISHED_MARKER}%s\\n' "$line"
exit "$rc"
"""
)


def _run(target: Transport, script: str, paths: str | None = None) -> tuple[bool, str]:
    """Run one script; whether it succeeded, and its stdout."""
    result = target.run(f"sh -c {shlex.quote(script)}", check=False, timeout=60, input_data=paths)
    return result.ok, result.stdout


def retire_tmuxinator_projects(target: Transport, workspace_paths: Sequence[str]) -> list[str]:
    """Remove the admin's generated discovery links and these workspaces' generated projects.

    Both commands always run, so one failure never leaves the rest of the VM
    uncleaned. A path that is not absolute or cannot travel one per line is skipped
    and counted. Returns a description of each failure, empty when everything
    finished; what succeeded stays done, and a rerun is safe.
    """
    sendable = [path for path in workspace_paths if path.startswith("/") and "\n" not in path and "\0" not in path]
    failures: list[str] = []
    if unsendable := len(workspace_paths) - len(sendable):
        failures.append(f"{output.count(unsendable, 'workspace path')} skipped as not absolute or not on one line")
    try:
        if not _run(target, _LINKS_SCRIPT)[0]:
            failures.append("the discovery links could not all be checked or removed")
    except SSHError:
        failures.append("the discovery-link command could not run over SSH")
    try:
        ok, stdout = _run(target, _PROJECTS_SCRIPT, "".join(f"{line}\n" for line in [_PATHS_SENTINEL, *sendable]))
    except SSHError:
        failures.append("the workspace-project command could not run over SSH")
    else:
        # The guest's output is input, so only a marker naming a line that was sent
        # counts, and only while no count of lines read says they were misread.
        lines = stdout.splitlines()
        counts = [int(match[1]) for line in lines if (match := _FINISHED_LINE.fullmatch(line))]
        read_every_path = counts == [len(sendable)]
        numbers = [int(match[1]) for line in lines if (match := _UNFINISHED_LINE.fullmatch(line))]
        if counts and not read_every_path:
            numbers = []
        unfinished = list(dict.fromkeys(sendable[number - 1] for number in numbers if number <= len(sendable)))
        if unfinished:
            failures.append(f"the projects in {', '.join(unfinished)} could not be checked or removed")
        if not read_every_path or (not ok and not unfinished):
            failures.append("the workspace projects could not all be checked or removed")
    return failures
