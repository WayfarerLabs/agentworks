"""Removal of the workspace tmuxinator projects that releases up to 0.19 generated.

Those releases wrote ``.tmuxinator.yml`` into each workspace and linked it from the
admin's ``~/.config/tmuxinator/`` as ``ws-<name>-console.yml``. Admin-side
configuration does not belong in workspace content, so the feature is removed and
``vm reinit`` retires what it left behind:

- Every ``ws-*-console.yml`` entry in the admin's ``~/.config/tmuxinator/`` that is a
  symlink whose target ends in ``/.tmuxinator.yml``, as every generated one did, is
  removed, dangling or not. Only the link goes; its target is never followed.
- A workspace's ``.tmuxinator.yml`` is removed when it is a regular file that starts
  with the header those releases wrote. Only that many bytes are compared. Anything
  else stays.

Both commands run under ``sh -c`` as the admin, so the admin's login shell never
parses them, and both always run. The workspace paths travel as arguments, so
nothing on stdin, such as a startup file of the admin's shell reading it, can change
them. Whether a path can be judged is the kernel's answer, never one worked out from
the path's text: a directory the admin cannot enter, a link that leads nowhere or
through a directory the admin cannot search, a project file that cannot be read and
a failed removal stay in place and count as failures. The caller warns once, naming
the workspaces the project command reports it could not finish; when that command
cannot run, or fails without naming any, the warning says so instead.
"""

from __future__ import annotations

import re
import shlex
from typing import TYPE_CHECKING

from agentworks import output
from agentworks.ssh import SSHError

if TYPE_CHECKING:
    from collections.abc import Sequence

    from agentworks.transports import Transport

_GENERATED_HEADER = b"# Generated by agentworks. Changes will be overwritten.\n"
_UNFINISHED_MARKER = "AGW_TMUXINATOR_UNFINISHED="
_UNFINISHED_LINE = re.compile(f"{_UNFINISHED_MARKER}([1-9][0-9]{{0,8}})")

# Each script records a failure in ``rc`` and keeps going, so one entry cannot hide
# another's failure or stop the rest. A test that is merely false never sets it;
# being unable to search or read something does.
#
# Both scripts first try to enter a directory with ``cd -P`` in a subshell, which
# succeeds only when the kernel lets the admin reach and search it. When it fails,
# ``vacant`` says whether the kernel shows nothing can be there: the path exists as
# something other than a directory, or it does not exist (and is not a link) and the
# nearest existing ancestor can be entered or is not a directory. Anything else, such
# as a directory the admin cannot search or a link that leads nowhere or through one,
# cannot be judged.
_VACANT_FUNCTION = """\
vacant() {
  if [ -e "$1" ]; then [ ! -d "$1" ]; return; fi
  [ ! -L "$1" ] || return 1
  parent=${1%/*}
  (cd -P -- "${parent:-/}") 2>/dev/null || vacant "${parent:-/}"
}
"""

# ``$(...)`` strips every trailing newline, and a link's target may end in one, so
# ``x`` guards the output and ``%??`` drops it with the one newline readlink adds,
# leaving the exact target. A failed readlink leaves it empty.
_LINKS_SCRIPT = (
    _VACANT_FUNCTION
    + """\
dir="$HOME/.config/tmuxinator"
if ! (cd -P -- "$dir") 2>/dev/null; then
  vacant "$dir" && exit 0
  exit 1
fi
[ -r "$dir" ] || exit 1
rc=0
for link in "$dir"/ws-*-console.yml; do
  target=$(readlink -- "$link" 2>/dev/null && printf x)
  case ${target%??} in
    */.tmuxinator.yml) rm -f -- "$link" || rc=1 ;;
  esac
done
exit "$rc"
"""
)

# Workspace paths arrive as arguments. ``[ -f ]`` and ``[ ! -L ]`` keep a FIFO, a
# directory or a link away from ``cmp``, which exits 1 on a difference and 2 when it
# cannot read. Each workspace the script could not finish is reported by its argument
# position on a marker line of its own, so the caller names it from the path it sent
# rather than from output that line-ending translation may have changed; the leading
# newline keeps a marker off any line the admin's shell printed without ending it.
_PROJECTS_SCRIPT = (
    _VACANT_FUNCTION
    + f"""\
header={shlex.quote(_GENERATED_HEADER.decode())}
rc=0
position=0
unfinished() {{ rc=1; printf '\\n{_UNFINISHED_MARKER}%s\\n' "$position"; }}
for workspace do
  position=$((position + 1))
  if (cd -P -- "$workspace") 2>/dev/null; then
    project="$workspace/.tmuxinator.yml"
    if [ -f "$project" ] && [ ! -L "$project" ]; then
      printf %s "$header" | cmp -s -n {len(_GENERATED_HEADER)} -- "$project" -
      case $? in
        0) rm -f -- "$project" || unfinished ;;
        1) ;;
        *) unfinished ;;
      esac
    fi
  elif ! vacant "$workspace"; then
    unfinished
  fi
done
exit "$rc"
"""
)


def _run(target: Transport, script: str, *arguments: str) -> tuple[bool, str]:
    """Run one script with these arguments and stdin closed; whether it succeeded, and its stdout."""
    command = shlex.join(["sh", "-c", script, "sh", *arguments])
    result = target.run(command, check=False, timeout=60)
    return result.ok, result.stdout


def retire_tmuxinator_projects(target: Transport, workspace_paths: Sequence[str]) -> list[str]:
    """Remove the admin's generated discovery links and these workspaces' generated projects.

    Both commands always run, so one failure never leaves the rest of the VM
    uncleaned. A path that is not absolute, or holds a NUL byte no argument can
    carry, is skipped and counted. Returns a description of each failure, empty
    when everything finished; what succeeded stays done, and a rerun is safe.
    """
    sendable = [path for path in workspace_paths if path.startswith("/") and "\0" not in path]
    failures: list[str] = []
    if unsendable := len(workspace_paths) - len(sendable):
        failures.append(f"{output.count(unsendable, 'workspace path')} skipped as not absolute or holding a NUL byte")
    try:
        if not _run(target, _LINKS_SCRIPT)[0]:
            failures.append("the discovery links could not all be checked or removed")
    except SSHError:
        failures.append("the discovery-link command could not run over SSH")
    try:
        ok, stdout = _run(target, _PROJECTS_SCRIPT, *sendable)
    except SSHError:
        failures.append("the workspace-project command could not run over SSH")
    else:
        # The guest's output is input, so only a whole marker line naming an argument
        # that was sent counts.
        numbers = [int(match[1]) for line in stdout.splitlines() if (match := _UNFINISHED_LINE.fullmatch(line))]
        unfinished = list(dict.fromkeys(sendable[number - 1] for number in numbers if number <= len(sendable)))
        if unfinished:
            failures.append(f"the projects in {', '.join(unfinished)} could not be checked or removed")
        elif not ok:
            failures.append("the workspace projects could not all be checked or removed")
    return failures
