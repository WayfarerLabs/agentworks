"""Removal of the workspace tmuxinator projects that releases up to 0.19 generated.

Those releases wrote ``.tmuxinator.yml`` into each workspace and linked it from the
admin's ``~/.config/tmuxinator/`` as ``ws-<name>-console.yml``. Admin-side
configuration does not belong in workspace content, so the feature is removed and
``vm reinit`` retires what it left behind:

- Every ``ws-*-console.yml`` entry in the admin's ``~/.config/tmuxinator/`` that is a
  symlink to a ``.tmuxinator.yml`` is removed, dangling or not. Only the link goes;
  its target is never followed.
- A workspace's ``.tmuxinator.yml`` is removed when it is a regular file that starts
  with the header those releases wrote. Only that many bytes are compared. Anything
  else stays.

The commands run under ``sh -c`` as the admin, so the admin's login shell never
parses them.
"""

from __future__ import annotations

import shlex
from typing import TYPE_CHECKING

from agentworks.ssh import SSHError

if TYPE_CHECKING:
    from collections.abc import Sequence

    from agentworks.transports import Transport

_GENERATED_HEADER = b"# Generated by agentworks. Changes will be overwritten.\n"

#: Workspaces handled per command, keeping each command line bounded.
PROJECTS_PER_COMMAND = 50

# Each script records a failed removal in ``rc`` and keeps going, so one entry
# cannot hide another's failure or stop the rest; a false test never sets it.
_LINKS_SCRIPT = """\
dir="$HOME/.config/tmuxinator"
[ -d "$dir" ] || exit 0
rc=0
for link in "$dir"/ws-*-console.yml; do
  if [ -L "$link" ]; then
    case "$(readlink -- "$link")" in
      */.tmuxinator.yml) rm -f -- "$link" || rc=1 ;;
    esac
  fi
done
exit "$rc"
"""


def _projects_script(workspace_paths: Sequence[str]) -> str:
    header = shlex.quote(_GENERATED_HEADER.decode())
    lines = [f"header={header}", "rc=0"]
    for path in workspace_paths:
        project = shlex.quote(f"{path}/.tmuxinator.yml")
        lines.append(
            f"if [ -f {project} ] && [ ! -L {project} ] && "
            f'printf %s "$header" | cmp -s -n {len(_GENERATED_HEADER)} -- {project} -; '
            f"then rm -f -- {project} || rc=1; fi"
        )
    lines.append('exit "$rc"')
    return "\n".join(lines) + "\n"


def _failed(target: Transport, script: str) -> int | None:
    """Run one script; the exit status when it did not succeed, else ``None``."""
    result = target.run(f"sh -c {shlex.quote(script)}", check=False, timeout=60)
    return None if result.ok else result.returncode


def retire_tmuxinator_projects(target: Transport, workspace_paths: Sequence[str]) -> None:
    """Remove the admin's generated discovery links and these workspaces' generated projects.

    Every command runs even after one fails, so one bad workspace never leaves the
    rest of the VM uncleaned. Raises one ``SSHError`` naming the first failure;
    what succeeded stays done, and a rerun is safe.
    """
    scripts = [_LINKS_SCRIPT] + [
        _projects_script(workspace_paths[start : start + PROJECTS_PER_COMMAND])
        for start in range(0, len(workspace_paths), PROJECTS_PER_COMMAND)
    ]
    failures = [code for script in scripts if (code := _failed(target, script)) is not None]
    if failures:
        raise SSHError(f"{len(failures)} of {len(scripts)} commands did not complete (first exit {failures[0]})")
