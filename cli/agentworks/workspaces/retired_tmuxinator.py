"""Removal of the workspace tmuxinator projects that releases up to 0.19 generated.

Those releases wrote ``.tmuxinator.yml`` into each workspace and linked it from the
admin's ``~/.config/tmuxinator/`` as ``ws-<name>-console.yml``. Admin-side
configuration does not belong in workspace content, so the feature is removed and
``vm reinit`` retires what it left behind:

- Every ``ws-*-console.yml`` entry in the admin's ``~/.config/tmuxinator/`` that is a
  symlink to a ``.tmuxinator.yml`` is removed, dangling or not. Only the link goes;
  its target is never followed.
- A workspace's ``.tmuxinator.yml`` is removed when it is a regular file that starts
  with the header those releases wrote. Only that many bytes are compared. Anything
  else stays.

Both commands run under ``sh -c`` as the admin, so the admin's login shell never
parses them, and both always run. A discovery directory that cannot be read or
searched, a project file that cannot be read and anything an unsearchable directory
hides stay in place and count as failures, as does a failed removal. The caller
warns once, naming the workspaces the project command reports it could not finish;
when that command cannot run or fails without reporting any, the warning says so
instead.
"""

from __future__ import annotations

import shlex
from typing import TYPE_CHECKING

from agentworks import output
from agentworks.ssh import SSHError

if TYPE_CHECKING:
    from collections.abc import Sequence

    from agentworks.transports import Transport

_GENERATED_HEADER = b"# Generated by agentworks. Changes will be overwritten.\n"
_UNFINISHED_MARKER = "AGW_TMUXINATOR_UNFINISHED="

# Each script records a failure in ``rc`` and keeps going, so one entry cannot hide
# another's failure or stop the rest. A test that is merely false never sets it;
# being unable to search or read something does.
#
# A test on a path is also false when an unsearchable ancestor hides the path, so
# both scripts start with ``hidden``, the one rule for absent versus hidden: it walks
# up from the path's parent to the nearest ancestor it can see, and the path is hidden
# when that ancestor is a directory it cannot search. Otherwise the path is absent or
# visible, so a visible path is never examined itself.
# Callers canonicalize first with ``realpath -m``, which resolves every link it can
# reach and keeps the rest literal, so a link into an unsearchable directory walks
# up from its target rather than stopping at the link.
_HIDDEN_FUNCTION = """\
hidden() {
  up="${1%/*}"
  until [ -e "$up" ]; do
    case $up in */*) up="${up%/*}" ;; *) return 1 ;; esac
  done
  [ -d "$up" ] && [ ! -x "$up" ]
}
"""

_LINKS_SCRIPT = (
    _HIDDEN_FUNCTION
    + """\
dir="$HOME/.config/tmuxinator"
if [ ! -d "$dir" ]; then
  hidden "$(realpath -m -- "$dir")" && exit 1
  exit 0
fi
[ -x "$dir" ] && [ -r "$dir" ] || exit 1
rc=0
for link in "$dir"/ws-*-console.yml; do
  case "$(readlink -- "$link" 2>/dev/null)" in
    */.tmuxinator.yml) rm -f -- "$link" || rc=1 ;;
  esac
done
exit "$rc"
"""
)

# Workspace paths arrive one per line on stdin. ``[ -f ]`` and ``[ ! -L ]`` keep a
# FIFO, a directory or a link away from ``cmp``, which exits 1 on a difference and 2
# when it cannot read. A project hidden by an unsearchable directory, whether its
# workspace or one above it, counts as a failure too. Each workspace the script
# could not finish is reported on its own marker line.
_PROJECTS_SCRIPT = (
    _HIDDEN_FUNCTION
    + f"""\
header={shlex.quote(_GENERATED_HEADER.decode())}
rc=0
unfinished() {{ rc=1; printf '\\n{_UNFINISHED_MARKER}%s\\n' "$workspace"; }}
while IFS= read -r workspace; do
  project="$workspace/.tmuxinator.yml"
  if [ -f "$project" ] && [ ! -L "$project" ]; then
    printf %s "$header" | cmp -s -n {len(_GENERATED_HEADER)} -- "$project" -
    case $? in
      0) rm -f -- "$project" || unfinished ;;
      1) ;;
      *) unfinished ;;
    esac
  elif hidden "$(realpath -m -- "$workspace")/.tmuxinator.yml"; then
    unfinished
  fi
done
exit "$rc"
"""
)


def _run(target: Transport, script: str, paths: str | None = None) -> tuple[bool, str]:
    """Run one script; whether it succeeded, and its stdout."""
    result = target.run(f"sh -c {shlex.quote(script)}", check=False, timeout=60, input_data=paths)
    return result.ok, result.stdout


def retire_tmuxinator_projects(target: Transport, workspace_paths: Sequence[str]) -> list[str]:
    """Remove the admin's generated discovery links and these workspaces' generated projects.

    Both commands always run, so one failure never leaves the rest of the VM
    uncleaned. A path that cannot travel one per line is skipped and counted. Returns
    a description of each failure, empty when everything finished; what succeeded
    stays done, and a rerun is safe.
    """
    sendable = [path for path in workspace_paths if "\n" not in path and "\0" not in path]
    failures: list[str] = []
    if unsendable := len(workspace_paths) - len(sendable):
        failures.append(f"{output.count(unsendable, 'workspace path')} cannot be sent one per line")
    try:
        if not _run(target, _LINKS_SCRIPT)[0]:
            failures.append("the discovery links could not all be checked or removed")
    except SSHError:
        failures.append("the discovery-link command could not run over SSH")
    try:
        ok, stdout = _run(target, _PROJECTS_SCRIPT, "".join(f"{path}\n" for path in sendable))
    except SSHError:
        failures.append("the workspace-project command could not run over SSH")
    else:
        unfinished = [
            line.removeprefix(_UNFINISHED_MARKER) for line in stdout.splitlines() if line.startswith(_UNFINISHED_MARKER)
        ]
        if unfinished:
            failures.append(f"the projects in {', '.join(unfinished)} could not be checked or removed")
        elif not ok:
            failures.append("the workspace projects could not all be checked or removed")
    return failures
