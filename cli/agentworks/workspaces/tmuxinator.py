"""Tmuxinator config generation for workspace consoles.

Agentworks owns the workspace .tmuxinator.yml file. It is regenerated from DB
state on any structural change (session create/delete/resume, agent
create/delete). Manual edits will be overwritten.

The generated config produces a workspace console: an admin-shell window plus
one window per session. Session windows attach to the session's locked-down
tmux session using the same wrapper pattern as the VM console.
"""

from __future__ import annotations

import shlex
from typing import TYPE_CHECKING

from agentworks.execution.requests import Command
from agentworks.sessions.multi_console import ADMIN_SHELL_WINDOW
from agentworks.sessions.tmux import exact_tmux_target, tmux_cmd
from agentworks.vms.home_layout import TMUXINATOR_CONFIG_DIR
from agentworks.workspaces.guest import PROBE_DEADLINE, addressable_workspace_path, script

if TYPE_CHECKING:
    from agentworks.db import SessionRow
    from agentworks.execution.access import VMAccess
    from agentworks.execution.requests import Script

GENERATED_HEADER = "# Generated by agentworks. Changes will be overwritten."

CONFIG_MODE = 0o600
"""The generated file's mode: only its admin reads it, as when it was copied from a private temporary file."""

CONFIG_NAME = ".tmuxinator.yml"
"""The generated config's name in the workspace directory."""


def console_session_name(ws_name: str) -> str:
    """Return the tmux session name for a workspace console."""
    return f"ws-{ws_name}-console"


def config_path(workspace_path: str) -> str:
    """The generated config in the workspace itself, normalized.

    A stored workspace path can carry a trailing ``/``, a ``.`` component or a
    leading ``//`` (a row from an earlier release), which the file operations
    refuse, so the path is normalized first; one that is not absolute or has a
    ``..`` component is a ``ValidationError``
    (``guest.addressable_workspace_path``).
    """
    return f"{addressable_workspace_path(workspace_path)}/{CONFIG_NAME}"


def config_link(home: str, ws_name: str) -> str:
    """The link in the admin's tmuxinator directory through which tmuxinator finds the console by name."""
    return f"{home}/{TMUXINATOR_CONFIG_DIR}/{console_session_name(ws_name)}.yml"


def write_config(access: VMAccess, workspace_path: str, text: str) -> None:
    """Replace the workspace's generated config with ``text``, as the admin whose ``access`` this is."""
    access.files(deadline=PROBE_DEADLINE).write(
        config_path(workspace_path), text.encode(), mode=CONFIG_MODE, parent_mode=0o755
    )


def publish_tmuxinator_config(
    access: VMAccess, *, home: str, ws_name: str, workspace_path: str, text: str, replace_link: bool
) -> None:
    """Write the generated config and link it from the admin's tmuxinator directory under ``home``.

    ``replace_link`` replaces whatever is at the link (``ln -sf``), for a
    workspace whose earlier link it supersedes; without it an existing entry
    fails the link and is left as it is.
    """
    write_config(access, workspace_path, text)
    link_config(access, home=home, ws_name=ws_name, workspace_path=workspace_path, replace_link=replace_link)


def link_config(access: VMAccess, *, home: str, ws_name: str, workspace_path: str, replace_link: bool) -> None:
    """Link the generated config from the admin's tmuxinator directory under ``home``, creating the directory.

    ``replace_link`` is :func:`publish_tmuxinator_config`'s.
    """
    access.files(deadline=PROBE_DEADLINE).ensure_directory(f"{home}/{TMUXINATOR_CONFIG_DIR}", mode=0o755)
    flags = "-sf" if replace_link else "-s"
    access.run(
        Command(("ln", flags, "--", config_path(workspace_path), config_link(home, ws_name)), deadline=PROBE_DEADLINE),
        check=True,
    )


def remove_config(access: VMAccess, *, home: str, ws_name: str, workspace_path: str) -> None:
    """Remove both managed tmuxinator projections for a disabled workspace.

    ``home`` is the admin's, whose ``access`` this is. A removal that fails
    is left for the next regeneration; one whose outcome is not known raises.
    """
    access.run(
        Command(("rm", "-f", "--", config_path(workspace_path), config_link(home, ws_name)), deadline=PROBE_DEADLINE)
    ).require_completed(access.vm_name)


def remove_link_to(home: str, ws_name: str, workspace_path: str) -> Script:
    """Removes the console link under ``home`` while it points at the config in ``workspace_path``.

    Agentworks writes an absolute target, and an earlier release wrote it from
    the stored path as spelled, so both sides are compared canonical without
    following links (``realpath -s -m``): a row spelled with a ``..`` or a
    trailing ``/`` still matches the link written from it. A relative target is
    never ours, and ``realpath`` would read it from the request's directory
    rather than the link's.
    """
    return script(
        'if test -L "$1"; then t=$(readlink -- "$1"); case $t in /*)\n'
        '  if test "$(realpath -s -m -- "$t")" = "$(realpath -s -m -- "$2/$3")"; then rm -- "$1"; fi ;; esac; fi',
        config_link(home, ws_name),
        workspace_path,
        CONFIG_NAME,
        deadline=PROBE_DEADLINE,
    )


def remove_link(home: str, ws_name: str) -> Script:
    """Removes the console link under ``home`` whatever it points at, never following it.

    For a workspace whose stored path names no one directory: the link's name
    is the workspace's own, so it is removed without comparing its target.
    Anything there that is not a link is left.
    """
    return script('if test -L "$1"; then rm -f -- "$1"; fi', config_link(home, ws_name), deadline=PROBE_DEADLINE)


def generate_config(
    ws_name: str,
    workspace_path: str,
    sessions: list[SessionRow] | None = None,
    socket_paths: dict[str, str | None] | None = None,
) -> str:
    """Generate a tmuxinator YAML config for a workspace.

    Produces an admin-shell window plus one window per session. Session windows
    use a wrapper that attaches to the session's locked-down tmux session.

    *socket_paths* overrides ``session.socket_path`` when provided (used to
    supply derived paths for migrated sessions with NULL socket_path).
    """
    lines = [
        GENERATED_HEADER,
        f"name: {console_session_name(ws_name)}",
        f"root: {workspace_path}",
        "on_project_start: tmux set remain-on-exit on",
        "windows:",
        # Quoted so YAML doesn't choke on the leading '--' (sentinel form
        # chosen to be impossible for any session name; see ADMIN_SHELL_WINDOW).
        f'  - "{ADMIN_SHELL_WINDOW}":',
        "      panes:",
        '        - ""',
    ]

    paths = socket_paths or {}
    for session in sessions or []:
        q_session = shlex.quote(session.name)
        q_exact_session = exact_tmux_target(session.name)
        sock = paths.get(session.name, session.socket_path)
        # Wrapper: unset TMUX for nesting, loop attach while session exists
        has_cmd = tmux_cmd(f"has-session -t {q_exact_session}", sock)
        attach_cmd = tmux_cmd(f"attach -t {q_exact_session}", sock)
        wrapper = (
            f"unset TMUX; "
            f"while {has_cmd} 2>/dev/null; do "
            f"{attach_cmd}; "
            f"sleep 0.5; "
            f"done; "
            f"echo 'Session {q_session} has ended. Press enter to close.'; "
            f"read"
        )
        lines.extend(
            [
                f'  - "{session.name}":',
                "      panes:",
                f"        - {wrapper}",
            ]
        )

    lines.append("")  # trailing newline
    return "\n".join(lines)
