def _replace_call(target: _Guest, number: int, outcome: Result | BaseException) -> list[Command]:
    """Make the ``number``th command (the links one is first) return or raise
    ``outcome`` instead of running; every other command runs for real. Returns the
    commands as they are issued."""
    real_answer = target.vm.answer
    assert real_answer is not None
    calls: list[Command] = []

    def replaced(call: Call) -> Result | BaseException | None:
        assert isinstance(call.request, Command)
        calls.append(call.request)
        return real_answer(call) if len(calls) != number else outcome

    target.vm.answer = replaced
    return calls


def _project_and_link(workspace: Path, entries: Path) -> tuple[Path, Path]:
    project = workspace / ".tmuxinator.yml"
    project.write_text(_GENERATED)
    link = entries / "ws-proj-console.yml"
    link.symlink_to(project)
    return project, link


