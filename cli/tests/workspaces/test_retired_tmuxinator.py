    try:
        _reinit(db, target)
    finally:
        locked.chmod(0o755)

    assert shlex.split(target.commands[1])[4:] == [str(locked), str(workspace)]
    assert not (workspace / ".tmuxinator.yml").exists()
    assert len(captured_output.warnings) == 1
    assert str(locked) in captured_output.warnings[0]


