@pytest.mark.parametrize(
    ("operation", "expected"),
    [(VMInitializationOperation.VM_REINIT, 1), (VMInitializationOperation.VM_CREATE, 0)],
)
def test_only_reinit_runs_the_removal(
    db: Database,
    make_config,  # noqa: ANN001
    monkeypatch: pytest.MonkeyPatch,
    operation: VMInitializationOperation,
    expected: int,
) -> None:
    from types import SimpleNamespace

    from agentworks.bootstrap import build_registry

    config = make_config()
    db.insert_vm("box", site="proxmox", hostname="box")
    calls: list[str] = []
    monkeypatch.setattr(
        "agentworks.vms.initializer.driver._retire_workspace_tmuxinator_projects",
        lambda db_, vm_name, target, logger: calls.append(vm_name),
    )
    target = MagicMock()
    target.run.return_value = SimpleNamespace(ok=True, returncode=0, stdout="", stderr="")

    _phase_b_setup(
        db,
        config,
        build_registry(config),
        ResolvedVMTemplate(name="default"),
        AdminConfig(name="default", username="operator", mise_activate=False),
        "box",
        target,
        (),
        "/home/operator",
        "operator",
        MagicMock(),
        debian_release=DebianRelease.TRIXIE,
        operation=operation,
    )

    assert calls == ["box"] * expected


