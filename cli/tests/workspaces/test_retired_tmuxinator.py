_HEADER = "# Generated by agentworks. Changes will be overwritten.\n"
_GENERATED = _HEADER + "name: ws-proj-console\nroot: /srv/proj\nwindows:\n"


@pytest.fixture
def guest(tmp_path: Path, db: Database) -> tuple[LocalFixtureTransport, Path, Path]:
    target = LocalFixtureTransport(tmp_path / "guest")
    workspace = tmp_path / "guest" / "workspaces" / "proj"
    workspace.mkdir(parents=True)
    entries = target.home / ".config" / "tmuxinator"
    entries.mkdir(parents=True)
    db.insert_vm("box", site="proxmox", hostname="box")
    db.insert_workspace("proj", vm_name="box", workspace_path=str(workspace), template="default", linux_group="ws-proj")
    return target, workspace, entries


def _reinit(db: Database, target: object) -> None:
    _retire_workspace_tmuxinator_projects(db, "box", target, Mock())  # type: ignore[arg-type]


@requires_guest_shell
def test_reinit_removes_discovery_links_into_workspaces_and_dangling_ones(
    db: Database, guest: tuple[LocalFixtureTransport, Path, Path]
) -> None:
    target, workspace, entries = guest
    (workspace / ".tmuxinator.yml").write_text("name: kept\n")
    live = entries / "ws-proj-console.yml"
    live.symlink_to(workspace / ".tmuxinator.yml")
    dangling = entries / "ws-deleted-console.yml"
    dangling.symlink_to(target.root / "gone" / ".tmuxinator.yml")
    own = entries / "ws-own-console.yml"
    own.write_text("name: own\n")
    elsewhere = target.root / "project.yml"
    elsewhere.write_text("name: elsewhere\n")
    other_link = entries / "ws-other-console.yml"
    other_link.symlink_to(elsewhere)
    unrelated = entries / "mine.yml"
    unrelated.symlink_to(workspace / ".tmuxinator.yml")

    _reinit(db, target)

    assert not live.is_symlink() and not dangling.is_symlink()
    assert (workspace / ".tmuxinator.yml").read_text() == "name: kept\n"
    assert own.read_text() == "name: own\n"
    assert other_link.is_symlink() and elsewhere.read_text() == "name: elsewhere\n"
    assert unrelated.is_symlink()


@requires_guest_shell
def test_reinit_removes_a_header_bearing_project_and_leaves_any_other(
    db: Database, guest: tuple[LocalFixtureTransport, Path, Path], tmp_path: Path
) -> None:
    target, workspace, _entries = guest
    project = workspace / ".tmuxinator.yml"
    project.write_text(_GENERATED + "  - extra:\n")
    modified = tmp_path / "guest" / "workspaces" / "modified"
    modified.mkdir()
    (modified / ".tmuxinator.yml").write_text("# Generated by agentworks. Edited by hand.\n" + _GENERATED)
    linked = tmp_path / "guest" / "workspaces" / "linked"
    linked.mkdir()
    target_file = target.root / "precious.yml"
    target_file.write_text(_GENERATED)
    (linked / ".tmuxinator.yml").symlink_to(target_file)
    truncated = tmp_path / "guest" / "workspaces" / "truncated"
    truncated.mkdir()
    (truncated / ".tmuxinator.yml").write_text(_HEADER.rstrip("\n"))
    for name, path in (("modified", modified), ("linked", linked), ("truncated", truncated)):
        db.insert_workspace(name, vm_name="box", workspace_path=str(path), template="default", linux_group=f"ws-{name}")

    _reinit(db, target)

    assert not project.exists()
    assert (modified / ".tmuxinator.yml").read_text().startswith("# Generated by agentworks. Edited")
    assert (linked / ".tmuxinator.yml").is_symlink() and target_file.read_text() == _GENERATED
    assert (truncated / ".tmuxinator.yml").exists()


def _workspace(db: Database, root: Path, name: str, content: str | None = _GENERATED) -> Path:
    path = root / name
    path.mkdir()
    if content is not None:
        (path / ".tmuxinator.yml").write_text(content)
    db.insert_workspace(name, vm_name="box", workspace_path=str(path), template="default", linux_group=f"ws-{name}")
    return path


