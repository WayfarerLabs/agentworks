@requires_guest_shell
def test_reinit_removes_discovery_links_into_workspaces_and_dangling_ones(
    db: Database, guest: tuple[LocalFixtureTransport, Path, Path]
) -> None:
    target, workspace, entries = guest
    (workspace / ".tmuxinator.yml").write_text("name: kept\n")
    live = entries / "ws-proj-console.yml"
    live.symlink_to(workspace / ".tmuxinator.yml")
    dangling = entries / "ws-deleted-console.yml"
    dangling.symlink_to(target.root / "gone" / ".tmuxinator.yml")
    own = entries / "ws-own-console.yml"
    own.write_text("name: own\n")
    elsewhere = target.root / "project.yml"
    elsewhere.write_text("name: elsewhere\n")
    other_link = entries / "ws-other-console.yml"
    other_link.symlink_to(elsewhere)
    unrelated = entries / "mine.yml"
    unrelated.symlink_to(workspace / ".tmuxinator.yml")

    _reinit(db, target)

    assert not live.is_symlink() and not dangling.is_symlink()
    assert (workspace / ".tmuxinator.yml").read_text() == "name: kept\n"
    assert own.read_text() == "name: own\n"
    assert other_link.is_symlink() and elsewhere.read_text() == "name: elsewhere\n"
    assert unrelated.is_symlink()


